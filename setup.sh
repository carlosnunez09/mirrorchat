#!/usr/bin/env bash
# Setup: reads values from .env; only asks for what's missing, then saves it to .env.
set -euo pipefail
cd "$(dirname "$0")"
REF="zxnjrcjpxkaefxvqnsjo"
touch .env; chmod 600 .env
set -a; . ./.env; set +a

save() { # save KEY VALUE
  grep -v "^$1=" .env > .env.tmp || true
  printf '%s=%s\n' "$1" "$2" >> .env.tmp; mv .env.tmp .env; chmod 600 .env
}

if [ -z "${SUPABASE_PUBLISHABLE_KEY:-}" ]; then
  echo "Publishable key: Dashboard > Project Settings > API Keys (sb_publishable_...). NOT the secret key."
  read -r -s -p "Paste publishable key (hidden): " SUPABASE_PUBLISHABLE_KEY; echo
  [ -n "$SUPABASE_PUBLISHABLE_KEY" ] || { echo "required"; exit 1; }
  save SUPABASE_PUBLISHABLE_KEY "$SUPABASE_PUBLISHABLE_KEY"
fi

cat > config.js <<EOC
// Generated by setup.sh from .env. Publishable key only; never the secret key.
window.SUPABASE_URL = "https://$REF.supabase.co";
window.SUPABASE_ANON_KEY = "$SUPABASE_PUBLISHABLE_KEY";
EOC
echo "✓ config.js written"

if [ -z "${SUPABASE_ACCESS_TOKEN:-}" ] && [ -z "${SKIP_SCHEMA:-}" ]; then
  echo "Access token: https://supabase.com/dashboard/account/tokens (Enter to skip schema)"
  read -r -s -p "Paste access token (hidden): " SUPABASE_ACCESS_TOKEN; echo
  if [ -n "$SUPABASE_ACCESS_TOKEN" ]; then save SUPABASE_ACCESS_TOKEN "$SUPABASE_ACCESS_TOKEN"
  else save SKIP_SCHEMA 1; echo "- skipped schema (delete SKIP_SCHEMA from .env to be asked again)"; fi
fi

if [ -n "${SUPABASE_ACCESS_TOKEN:-}" ]; then
  BODY=$(python3 -c 'import json,glob;print(json.dumps({"query":"\n".join(open(f).read() for f in sorted(glob.glob("schema*.sql")))}))')
  CODE=$(curl -s -o .resp.json -w "%{http_code}" -X POST \
    "https://api.supabase.com/v1/projects/$REF/database/query" \
    -H "Authorization: Bearer $SUPABASE_ACCESS_TOKEN" -H "Content-Type: application/json" -d "$BODY")
  if [ "$CODE" = "200" ] || [ "$CODE" = "201" ]; then echo "✓ schema applied"
  else echo "✗ schema failed (HTTP $CODE):"; cat .resp.json; echo; rm -f .resp.json; exit 1; fi
  rm -f .resp.json
fi

pgrep -f "http.server 8000" >/dev/null && echo "server already running: http://localhost:8000" \
  || { echo "serving at http://localhost:8000"; python3 -m http.server 8000; }
